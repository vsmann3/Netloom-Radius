"""Resolve upstream image tags to content digests; review image-lock.env before use."""
import json
import re
import urllib.request
from pathlib import Path

IMAGES = {
    "PYTHON_IMAGE": ("library/python", "3.13.16-slim-trixie"),
    "MARIADB_IMAGE": ("library/mariadb", "11.8.9"),
    "FREERADIUS_IMAGE": ("freeradius/freeradius-server", "3.2.10"),
}


def resolve(repository, tag):
    url = f"https://auth.docker.io/token?service=registry.docker.io&scope=repository:{repository}:pull"
    with urllib.request.urlopen(url, timeout=30) as response:
        token = json.load(response)["token"]
    request = urllib.request.Request(
        f"https://registry-1.docker.io/v2/{repository}/manifests/{tag}",
        headers={"Authorization": f"Bearer {token}", "Accept": ", ".join([
            "application/vnd.oci.image.index.v1+json", "application/vnd.docker.distribution.manifest.list.v2+json",
            "application/vnd.oci.image.manifest.v1+json", "application/vnd.docker.distribution.manifest.v2+json",
        ])},
    )
    with urllib.request.urlopen(request, timeout=30) as response:
        digest = response.headers["Docker-Content-Digest"]
    if not digest.startswith("sha256:") or len(digest) != 71:
        raise ValueError("Unexpected registry digest")
    return f"{repository.removeprefix('library/')}:{tag}@{digest}"


if __name__ == "__main__":
    lines = ["# Generated by scripts/lock_images.py; commit after reviewing upstream versions."]
    for name, (repository, tag) in IMAGES.items():
        lines.append(f"{name}={resolve(repository, tag)}")
    root = Path(__file__).resolve().parent.parent
    python_image = next(line.split("=", 1)[1] for line in lines if line.startswith("PYTHON_IMAGE="))
    dockerfile = root / "Dockerfile"
    updated, count = re.subn(r"^ARG PYTHON_IMAGE(?:=[^\n]*)?$", f"ARG PYTHON_IMAGE={python_image}",
                             dockerfile.read_text(encoding="utf-8"), flags=re.MULTILINE)
    if count != 1:
        raise ValueError("Expected one global PYTHON_IMAGE argument in Dockerfile")
    target = root / "image-lock.env"
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    dockerfile.write_text(updated, encoding="utf-8", newline="\n")
    print("Wrote image-lock.env and synchronized the Dockerfile default")
